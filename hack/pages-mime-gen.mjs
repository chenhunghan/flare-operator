// Generates internal/controller/pagesdeployment/mime_table.go: the extension → type table of
// mime@3.0.0 as bundled in wrangler (the Pages asset contentType, wrangler's validate walk:
// `contentType: getType(name) || "application/octet-stream"`).
//
//   node hack/pages-mime-gen.mjs <wrangler-dist/cli.js> | gofmt > internal/controller/pagesdeployment/mime_table.go
//
// The differential tools (hack/differential-tools.sh) install wrangler under
// ~/.cache/flare-operator/differential/wrangler-<version>.
import { readFileSync } from "node:fs";

const file = process.argv[2];
if (!file) {
  console.error("usage: node hack/pages-mime-gen.mjs <wrangler-dist/cli.js>");
  process.exit(2);
}
const lines = readFileSync(file, "utf8").split("\n");

// The bodies of mime/types/standard.js and mime/types/other.js: one `module2.exports = {…};` line
// each, right after the module's marker.
function table(marker) {
  const i = lines.findIndex((l) => l.includes(`"../../node_modules/.pnpm/mime@3.0.0/node_modules/mime/types/${marker}.js"(`));
  if (i < 0) throw new Error(`mime@3.0.0 types/${marker}.js not found`);
  for (let j = i; j < i + 5; j++) {
    const m = lines[j].match(/^\s*module2\.exports = (\{.*\});\s*$/);
    if (m) return { obj: JSON.parse(m[1]), line: j + 1 };
  }
  throw new Error(`types/${marker}.js: exports not found`);
}

const std = table("standard");
const other = table("other");

// Mime.prototype.define without force, in constructor order (standard, then other).
const types = Object.create(null);
for (const map of [std.obj, other.obj]) {
  for (let type in map) {
    const exts = map[type].map((e) => e.toLowerCase());
    type = type.toLowerCase();
    for (const ext of exts) {
      if (ext[0] === "*") continue;
      if (ext in types) throw new Error(`duplicate extension ${ext}`);
      types[ext] = type;
    }
  }
}

const version = (file.match(/wrangler-(\d+\.\d+\.\d+)/) || [])[1] || "unknown";
let out = `// Code generated by hack/pages-mime-gen.mjs; DO NOT EDIT.

package pagesdeployment

// mimeTypes is mime@3.0.0's extension → type table (mime.getType), as bundled in wrangler
// (SOURCED, relies: wrangler@${version}:wrangler-dist/cli.js#L${std.line} (types/standard.js) and
// #L${other.line} (types/other.js)).
var mimeTypes = map[string]string{
`;
for (const ext of Object.keys(types).sort()) {
  out += `\t${JSON.stringify(ext)}: ${JSON.stringify(types[ext])},\n`;
}
out += "}\n";
process.stdout.write(out);
